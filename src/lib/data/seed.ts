type Semilla = Omit<
  Producto,
  | "imagenes"
  | "esDemo"
  | "stockMinimo"
  | "actualizadoEn"
  | "activo"
  | "numValoraciones"
  | "creadoEn"
  | "destacado"
> & {
  stockMinimo?: number;
  activo?: boolean;
  numValoraciones?: number;
  destacado?: boolean;
  fecha: string;
};

function p(semilla: Semilla): Producto {
  const { fecha, stockMinimo, activo, numValoraciones, destacado, ...resto } = semilla;
  return {
    ...resto,
    imagenes: [`/productos/${resto.slug}.svg`],
    stockMinimo: stockMinimo ?? 5,
    activo: activo ?? true,
    destacado: destacado ?? false,
    numValoraciones: numValoraciones ?? Math.max(1, Math.round(resto.vendidos / 7)),
    esDemo: true,
    creadoEn: fecha,
    actualizadoEn: fecha,
  };
}

